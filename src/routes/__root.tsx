// Shows the uploaded Apex logo as the browser tab icon. The logo lives in a private bucket,
// so it is delivered through a signed URL; /favicon.ico stays as the fallback until it loads.
function TabIcon() {
  const { data: apex } = useQuery({ queryKey: ["apex"], queryFn: () => getApex() });
  const path = apex?.settings.logo_url;
  const { data: logoUrl } = useQuery({
    queryKey: ["logo", path],
    enabled: !!path,
    queryFn: async () => {
      const { data, error } = await supabase.storage
        .from("apex-logos")
        .createSignedUrl(path!, 3600);
      if (error) throw error;
      return data.signedUrl;
    },
    staleTime: 3000000,
  });

  useEffect(() => {
    if (!logoUrl) return;
    document.querySelectorAll<HTMLLinkElement>('link[rel~="icon"]').forEach((link) => {
      link.removeAttribute("type");
      link.href = logoUrl;
    });
  }, [logoUrl]);

  return null;
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <TabIcon />
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <ApexAuthProvider><Outlet /></ApexAuthProvider>
    </QueryClientProvider>
  );
}
